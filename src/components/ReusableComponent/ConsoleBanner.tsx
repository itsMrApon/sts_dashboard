const BANNER_FLAG = "__stsConsoleBannerShown";

export function ConsoleBanner() {
  useEffect(() => {
    const browserWindow = window as typeof window & { [BANNER_FLAG]?: boolean };
    if (browserWindow[BANNER_FLAG]) return;
    browserWindow[BANNER_FLAG] = true;

    const format = BANNER_LINES.map(() => "%c%s").join("\n\n");
    const args = BANNER_LINES.flatMap(({ color, art }) => [
      `color:${color};font-family:monospace;font-size:10px;line-height:1.1;font-weight:700;`,
      art,
    ]);
    console.log(format, ...args);
  }, []);

  return null;
}
